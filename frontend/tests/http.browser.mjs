/**
 * #13 real-stack browser suite: the real Vite app (default HTTP adapter) against the real FastAPI backend on a temp-file
 * SQLite database. Covers register -> login -> reload -> logout/revocation, live catalogue/filters/detail/availability,
 * 401 handling with return navigation, controlled network and invalid-response failures with retry, and duplicate-submit
 * protection, at 1440 and 390 px. Nothing is mocked: failures are provoked by stopping the real backend or by blocking
 * the browser's network route. Run: PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH=/path/to/chromium npm run test:browser:http
 */
import assert from 'node:assert/strict'
import { join } from 'node:path'
import { api, launchBrowser, outputFolder, startStack, writeJson } from './support/stack.mjs'
import { TOKEN_KEY, addDays, assertNoUnexpected, clubToday, createHelpers, newSink, newStudent, snap, watch } from './support/browserKit.mjs'

const output = outputFolder('http')
const sink = newSink()
const checks = []
const pass = (name) => { checks.push(name); console.log(`PASS ${name}`) }
const ALL_CODES = ['ACC-001', 'ACC-002', 'ACC-003', 'AUD-001', 'AUD-002', 'CAM-001', 'CAM-002', 'CAM-003', 'PRE-001', 'PRE-002']
let stack, browser, failureContext

try {
  stack = await startStack()
  browser = await launchBrowser()
  const T = clubToday()
  assert.equal(T, (await api(stack, '/api/v1/assets')).json.today, 'browser and backend agree on the Asia/Almaty club date')

  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 } })
    const page = await context.newPage()
    page.setDefaultTimeout(20_000)
    failureContext = { page, width }
    watch(page, `w${width}`, sink)
    const base = stack.frontendUrl
    const h = createHelpers(page, base)
    const requestsFrom = (index) => sink.requests.slice(index)
    const label = (text) => `${text} @${width}`

    // ---- default adapter is HTTP and shows live catalogue data ---------------------------------------------------
    await page.goto(`${base}/#/explore`)
    await h.heading('Explore')
    await page.locator('a.equipment-card').first().waitFor()
    assert.deepEqual(await h.codes(), ALL_CODES, 'the ten seeded units come from the backend')
    assert.equal(await page.locator('.demo-banner').count(), 0, 'no demo banner outside mock mode')
    assert.equal(await page.getByText('Demo controls').count(), 0)
    assert.ok(sink.requests.some((r) => r.label === `w${width}` && r.url.startsWith('/api/v1/assets')), 'catalogue read goes to /api/v1/assets')
    assert.ok(sink.responses.some((r) => r.label === `w${width}` && r.url === '/api/v1/assets' && r.status === 200))
    assert.equal(sink.requests.filter((r) => r.label === `w${width}`).every((r) => r.headers.authorization === undefined), true, 'anonymous browsing sends no bearer token')
    const camera03 = page.locator('a.equipment-card').filter({ hasText: 'CAM-003' })
    assert.match(await camera03.innerText(), /Maintenance · unavailable/)
    await h.noOverflow(label('explore'))
    await snap(page, join(output, `explore-${width}.png`))
    await page.goto(`${base}/#/signin`)
    await h.heading('Sign in')
    assert.equal(await page.getByText('Fictional demo accounts').count(), 0, 'demo credentials exist only in mock mode')
    assert.equal(await page.getByRole('button', { name: /^Fill / }).count(), 0)
    await h.noOverflow(label('sign in'))
    await snap(page, join(output, `signin-${width}.png`))
    pass(label('default adapter is HTTP: live seeded catalogue, no demo banner or demo credentials, anonymous requests'))

    // ---- register, reload keeps the session, logout revokes ------------------------------------------------------
    const student = newStudent(`s${width}`)
    const before = sink.requests.length
    await h.register(student.username, student.password)
    await page.getByText('Account created. You are signed in as a student.', { exact: true }).waitFor()
    const registerCall = requestsFrom(before).find((r) => r.method === 'POST' && r.url === '/api/v1/auth/register')
    assert.deepEqual(JSON.parse(registerCall.body), { username: student.username, password: student.password })
    assert.equal(registerCall.headers['content-type'], 'application/json')
    const token = await h.token()
    assert.match(token, /^[A-Za-z0-9_-]{32,}$/)
    const storage = await page.evaluate(() => ({ local: Object.keys(localStorage), cookie: document.cookie, href: location.href }))
    assert.deepEqual(storage.local, [], 'nothing in localStorage')
    assert.equal(storage.cookie, '')
    assert.equal(storage.href.includes(token), false, 'the token is never in the URL')
    assert.match(await h.accountName().innerText(), new RegExp(`${student.username}\\s+student`, 'i'))
    // The server really knows this session.
    assert.deepEqual((await api(stack, '/api/v1/auth/me', { token })).json.username, student.username)

    const beforeReload = sink.requests.length
    await page.reload()
    await h.accountName().waitFor()
    assert.match(await h.accountName().innerText(), new RegExp(student.username, 'i'))
    assert.equal(await h.token(), token, 'session survives a reload in the same tab')
    const meCall = requestsFrom(beforeReload).find((r) => r.url === '/api/v1/auth/me')
    assert.equal(meCall.headers.authorization, `Bearer ${token}`, 'reload restores the user through GET /auth/me with the bearer token')
    await snap(page, join(output, `signed-in-${width}.png`))

    await h.signOut()
    await page.getByText('Signed out. Your session has ended.', { exact: true }).waitFor()
    assert.equal(await h.token(), null, 'logout removes the local token')
    const reused = await api(stack, '/api/v1/auth/me', { token })
    assert.equal(reused.status, 401, 'logout revoked the server session: the old token no longer works')
    assert.equal(reused.json.code, 'UNAUTHENTICATED')
    await page.reload()
    await h.heading('Explore')
    assert.equal(await h.accountName().count(), 0, 'still signed out after reload')
    pass(label('register -> reload keeps session via bearer /auth/me -> logout revokes the old token (direct 401)'))

    // ---- login errors never look like success --------------------------------------------------------------------
    await page.goto(`${base}/#/signin`)
    await h.heading('Sign in')
    await page.getByLabel('Username', { exact: true }).fill(student.username)
    await page.getByLabel('Password', { exact: true }).fill('definitely-wrong-password')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.locator('.form-alert').filter({ hasText: 'Username or password is incorrect.' }).waitFor()
    assert.equal(await h.token(), null)
    assert.equal(await page.locator('.success-notice').count(), 0)
    assert.equal(await page.getByLabel('Username', { exact: true }).inputValue(), student.username, 'entered username is kept')
    await page.getByLabel('Username', { exact: true }).fill('a')
    await page.getByLabel('Password', { exact: true }).fill('short')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.locator('#username-error').waitFor()
    assert.equal(await page.locator('#password-error').isVisible(), true)
    assert.equal(await page.getByLabel('Username', { exact: true }).evaluate((el) => el === document.activeElement), true, 'focus moves to the first invalid field')
    await page.goto(`${base}/#/register`)
    await h.heading('Create an account')
    await page.getByLabel('Username', { exact: true }).fill(student.username.toUpperCase())
    await page.getByLabel('Password', { exact: true }).fill(student.password)
    await page.getByRole('button', { name: 'Create student account', exact: true }).click()
    await page.locator('#username-error').filter({ hasText: 'Choose a different username.' }).waitFor()
    assert.equal(await h.token(), null)
    await h.signIn(student.username, student.password)
    assert.notEqual(await h.token(), token, 'a new login issues a new token')
    pass(label('wrong credentials, field validation and duplicate username show contract errors with no session; login works again'))

    // ---- live catalogue filters, detail, maintenance, missing ----------------------------------------------------
    await h.go('explore')
    await page.locator('a.equipment-card').first().waitFor()
    await page.getByLabel('Search equipment').fill('tripod')
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 1)
    assert.deepEqual(await h.codes(), ['ACC-001'])
    await page.getByLabel('Search equipment').fill('')
    await page.getByRole('button', { name: 'Audio', exact: true }).click()
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 2)
    assert.deepEqual(await h.codes(), ['AUD-001', 'AUD-002'])
    await page.getByRole('button', { name: 'All equipment', exact: true }).click()
    await page.getByLabel('Start date', { exact: true }).fill(addDays(T, 1))
    await page.getByLabel('End date', { exact: true }).fill(addDays(T, 1))
    await page.waitForFunction(() => document.querySelector('.catalogue-results-label')?.textContent.includes('available for your dates'))
    assert.deepEqual(await h.codes(), ['ACC-001', 'ACC-002', 'ACC-003', 'AUD-002', 'CAM-001', 'PRE-001', 'PRE-002'], 'T+1 excludes CAM-002/AUD-001 (booked) and CAM-003 (maintenance)')
    const sentFilters = sink.requests.filter((r) => r.label === `w${width}` && r.url.includes('startDate=')).at(-1).url
    assert.match(sentFilters, new RegExp(`startDate=${addDays(T, 1)}&endDate=${addDays(T, 1)}`))
    await page.getByRole('button', { name: 'Cameras', exact: true }).click()
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 1)
    assert.deepEqual(await h.codes(), ['CAM-001'])
    await page.getByLabel('Start date', { exact: true }).fill(addDays(T, 2))
    await page.getByLabel('End date', { exact: true }).fill(addDays(T, 2))
    await page.getByText('No equipment to show.').waitFor()
    await page.getByRole('button', { name: 'Clear all filters' }).click()
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 10)
    await h.noOverflow(label('filtered catalogue'))
    pass(label('live catalogue: search, category, inclusive date availability and empty state come from backend data'))

    await page.getByRole('link', { name: 'View Field Camera · Unit 02, CAM-002', exact: true }).click()
    await h.heading('Check availability')
    await page.getByRole('heading', { name: 'Field Camera · Unit 02', level: 2 }).waitFor()
    for (const offset of [1, 2, 3]) assert.match(await (await h.calendarDay(addDays(T, offset))).getAttribute('aria-label'), /Occupied, unavailable/)
    assert.match(await (await h.calendarDay(addDays(T, 4))).getAttribute('aria-label'), /Available/)
    const pastAvailability = (await api(stack, '/api/v1/assets/camera-02/availability')).json
    assert.deepEqual(Object.keys(pastAvailability).sort(), ['assetId', 'days', 'horizonEnd', 'timeZone', 'today'])
    assert.deepEqual([...new Set(pastAvailability.days.flatMap((day) => Object.keys(day)))].sort(), ['date', 'state'], 'availability is anonymous: only date and state')
    assert.equal(sink.requests.filter((r) => r.url.startsWith('/api/v1/assets/') && r.label === `w${width}`).every((r) => r.headers.authorization === undefined), true, 'public reads never carry the token, even when signed in')
    await h.noOverflow(label('detail'))
    await snap(page, join(output, `detail-${width}.png`))

    await page.goto(`${base}/#/assets/camera-03`)
    await h.heading('Check availability')
    await page.getByText('Maintenance · unavailable for requests').waitFor()
    assert.match(await (await h.calendarDay(addDays(T, 2))).getAttribute('aria-label'), /Maintenance, unavailable/)
    assert.equal(await page.getByRole('button', { name: 'Request equipment', exact: true }).isDisabled(), true)
    await page.goto(`${base}/#/assets/no-such-unit`)
    await page.getByRole('heading', { name: 'Equipment not found.' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Retry detail' }).count(), 0, 'a missing unit is not retryable')
    assert.ok(sink.responses.some((r) => r.url === '/api/v1/assets/no-such-unit' && r.status === 404))
    pass(label('detail shows occupied days, anonymous availability, maintenance unit and the 404 missing-asset state'))

    // ---- 401: revoked session while using the app ------------------------------------------------------------------
    await h.go('explore')
    const stale = await h.token()
    await api(stack, '/api/v1/auth/logout', { method: 'POST', token: stale }) // revoke behind the page's back
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'My reservations' }).click()
    await page.getByText('Your session has ended. Sign in again to continue.').waitFor()
    assert.equal(await h.token(), null, '401 cleared the stale token')
    assert.equal(await h.accountName().count(), 0, '401 cleared the stale user')
    const again = page.getByRole('link', { name: 'Sign in again' })
    assert.match(await again.getAttribute('href'), /returnTo=reservations/)
    await page.getByRole('link', { name: 'Sign in to view reservations' }).waitFor()
    await h.noOverflow(label('401 notice'))
    await snap(page, join(output, `session-ended-${width}.png`))
    await again.click()
    await h.heading('Sign in')
    await page.getByLabel('Username', { exact: true }).fill(student.username)
    await page.getByLabel('Password', { exact: true }).fill(student.password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('heading', { name: 'Plan. Collect. Create.' }).waitFor()
    assert.match(page.url(), /#\/reservations$/, 'sign-in returned to the page the user was on')
    assert.equal(await page.getByText('Your session has ended').count(), 0, 'notice cleared by the new sign-in')

    // 401 while submitting on a public page: the entered booking is not lost and sign-in returns to the asset.
    await page.goto(`${base}/#/assets/presentation-02`)
    await h.heading('Check availability')
    const start = addDays(T, 30)
    await page.getByLabel('Start date', { exact: true }).fill(start)
    await page.getByLabel('End date', { exact: true }).fill(start)
    await page.getByLabel('Project purpose').fill('Screening night rehearsal')
    await api(stack, '/api/v1/auth/logout', { method: 'POST', token: await h.token() })
    await page.getByRole('button', { name: 'Request equipment', exact: true }).click()
    await page.getByText('Your session has ended. Sign in again to continue.').waitFor()
    assert.equal(await page.locator('.success-notice').count(), 0, '401 is never shown as success')
    assert.equal(await h.token(), null)
    const detailLink = page.getByRole('link', { name: 'Sign in to request equipment' })
    assert.match(decodeURIComponent(await detailLink.getAttribute('href')), /returnTo=assets\/presentation-02$/)
    assert.equal(await page.getByLabel('Project purpose').count(), 0, 'form is replaced by the sign-in offer')
    await detailLink.click()
    await h.heading('Sign in')
    await page.getByLabel('Username', { exact: true }).fill(student.username)
    await page.getByLabel('Password', { exact: true }).fill(student.password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await h.heading('Check availability')
    assert.match(page.url(), /#\/assets\/presentation-02$/)

    // Stale token found at start-up (expired or revoked while the tab was closed).
    await page.evaluate((key) => sessionStorage.setItem(key, 'not-a-real-token-not-a-real-token'), TOKEN_KEY)
    await page.reload()
    await page.getByText('Your session has ended. Sign in again to continue.').waitFor()
    assert.equal(await h.token(), null)
    assert.equal(await h.accountName().count(), 0)
    pass(label('401 (revoked mid-session on My reservations and on an asset form, and stale token at reload) clears credentials, offers sign-in, returns to the same page'))

    // ---- failures: browser network, invalid responses, real backend outage, retry -----------------------------------
    await h.signIn(student.username, student.password)
    await h.go('explore')
    await page.locator('a.equipment-card').first().waitFor()
    await page.route('**/api/v1/assets**', (route) => route.abort('failed'))
    await page.getByRole('button', { name: 'Audio', exact: true }).click()
    await page.getByText('Could not reach the GearShare server.').waitFor()
    assert.equal(await page.locator('a.equipment-card').count(), 0, 'no stale or mock equipment is shown instead of the error')
    assert.equal(await page.getByRole('button', { name: 'Retry equipment' }).isVisible(), true)
    await h.noOverflow(label('network error'))
    await snap(page, join(output, `network-error-${width}.png`))
    await page.unroute('**/api/v1/assets**')
    await page.getByRole('button', { name: 'Retry equipment' }).click()
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 2)
    assert.deepEqual(await h.codes(), ['AUD-001', 'AUD-002'])

    await page.route('**/api/v1/assets**', (route) => route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><title>GearShare</title><div id="root"></div>' }))
    await page.getByRole('button', { name: 'Accessories', exact: true }).click()
    await page.getByText('The GearShare server sent a response this app cannot use.').waitFor()
    assert.equal(await page.locator('a.equipment-card').count(), 0)
    await page.unroute('**/api/v1/assets**')
    await page.route('**/api/v1/assets**', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ items: [{ id: 'x' }], range: null }) }))
    await page.getByRole('button', { name: 'Presentation', exact: true }).click()
    await page.getByText('The GearShare server sent a response this app cannot use.').waitFor()
    await page.unroute('**/api/v1/assets**')
    await page.route('**/api/v1/assets**', (route) => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ code: 'SERVICE_UNAVAILABLE', message: 'The service is temporarily unavailable. Try again.' }) }))
    await page.getByRole('button', { name: 'Cameras', exact: true }).click()
    await page.getByText('The service is temporarily unavailable. Try again.').waitFor()
    await page.unroute('**/api/v1/assets**')
    await page.getByRole('button', { name: 'Retry equipment' }).click()
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 3)
    pass(label('aborted network, HTML-instead-of-JSON, wrong-shape JSON and 500 show retryable errors (no cards, no mock data); retry recovers'))

    // A real outage: stop the backend. The dev proxy answers 502 with no body.
    await stack.stopBackend()
    await page.reload()
    await page.getByText('The GearShare server is unavailable right now.').first().waitFor()
    assert.equal(await page.locator('a.equipment-card').count(), 0)
    const retrySession = page.getByRole('button', { name: 'Retry session' })
    await retrySession.waitFor()
    assert.ok(await h.token(), 'an outage is not an expired session: the token is kept')
    assert.equal(await h.accountName().count(), 0, 'the user is not shown as signed in while the session cannot be verified')
    await h.noOverflow(label('backend outage'))
    await snap(page, join(output, `backend-down-${width}.png`))
    // Sign-in during the outage fails honestly and keeps the entered values.
    await page.goto(`${base}/#/signin`)
    await h.heading('Sign in')
    await page.getByLabel('Username', { exact: true }).fill(student.username)
    await page.getByLabel('Password', { exact: true }).fill(student.password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.locator('.form-alert').filter({ hasText: 'The GearShare server is unavailable right now.' }).waitFor()
    assert.equal(await page.locator('.success-notice').count(), 0)
    assert.equal(await page.getByLabel('Username', { exact: true }).inputValue(), student.username)
    assert.equal(await page.getByLabel('Password', { exact: true }).inputValue(), student.password)
    await stack.startBackend()
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByText(`Signed in as ${student.username}.`).waitFor()
    // Persistence smoke: sessions and accounts are in SQLite, so a restarted backend still honours the live token.
    const liveToken = await h.token()
    await stack.restartBackend()
    assert.equal((await api(stack, '/api/v1/auth/me', { token: liveToken })).status, 200, 'session survives a real backend restart')
    await page.reload()
    await h.accountName().waitFor()
    assert.match(await h.accountName().innerText(), new RegExp(student.username, 'i'))
    // Reload during an outage keeps the token; "Retry session" restores the user once the backend is back.
    await stack.stopBackend()
    await page.reload()
    await retrySession.waitFor()
    await stack.startBackend()
    await retrySession.click()
    await h.accountName().waitFor()
    assert.match(await h.accountName().innerText(), new RegExp(student.username, 'i'))
    await h.go('explore')
    await page.waitForFunction(() => document.querySelectorAll('a.equipment-card').length === 10)
    pass(label('real backend outage: retryable errors without mock data, token kept, sign-in fails honestly, restart restores session and catalogue'))

    // ---- slow submit cannot be repeated ---------------------------------------------------------------------------
    await h.signOut()
    await page.goto(`${base}/#/signin`)
    await h.heading('Sign in')
    await page.getByLabel('Username', { exact: true }).fill(student.username)
    await page.getByLabel('Password', { exact: true }).fill(student.password)
    await page.route('**/api/v1/auth/login', async (route) => { await new Promise((resolve) => setTimeout(resolve, 900)); await route.continue() })
    const loginsBefore = sink.requests.filter((r) => r.url === '/api/v1/auth/login' && r.label === `w${width}`).length
    await page.getByRole('button', { name: 'Sign in', exact: true }).dblclick()
    await page.getByRole('button', { name: 'Signing in…' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Signing in…' }).isDisabled(), true)
    assert.equal(await page.getByLabel('Password', { exact: true }).isDisabled(), true)
    await h.accountName().waitFor()
    await page.unroute('**/api/v1/auth/login')
    assert.equal(sink.requests.filter((r) => r.url === '/api/v1/auth/login' && r.label === `w${width}`).length - loginsBefore, 1, 'one login request despite a double click on a slow response')
    pass(label('slow sign-in disables the form and a double click sends exactly one request'))

    await h.noOverflow(label('final'))
    await context.close()
  }

  assertNoUnexpected(sink)
  const unexpectedFailures = sink.failedRequests.filter((entry) => !/api\/v1\/assets/.test(entry))
  assert.deepEqual(unexpectedFailures, [], 'only the deliberately aborted catalogue reads failed at transport level')
  pass('no uncaught page errors or unexpected console errors; API failures only where provoked')
  writeJson(output, 'results.json', { checks, date: new Date().toISOString(), browser: browser.version(), resourceErrors: sink.resourceErrors.length, responses: sink.responses.length, statuses: Object.fromEntries([...new Set(sink.responses.map((r) => r.status))].sort().map((status) => [status, sink.responses.filter((r) => r.status === status).length])) })
  console.log(`All ${checks.length} HTTP browser checks passed.`)
} catch (error) {
  if (failureContext?.page && !failureContext.page.isClosed()) await failureContext.page.screenshot({ path: join(output, 'failure.png'), fullPage: true }).catch(() => {})
  writeJson(output, 'failure.json', { checks, error: String(error), stack: error.stack, sink: { ...sink, requests: sink.requests.slice(-40), responses: sink.responses.slice(-40) }, logs: stack?.logs() })
  console.error(error)
  process.exitCode = 1
} finally {
  await browser?.close()
  await stack?.stop()
}
