    await coordinator.getByText('Check the highlighted equipment fields.', { exact: true }).waitFor()
    for (const field of ['name', 'inventoryCode', 'location']) await coordinator.locator(`#inventory-${field}-error`).waitFor()
    await coordinator.waitForFunction(() => document.activeElement?.id === 'inventory-name')
    await coordinator.getByLabel('Equipment name', { exact: true }).fill('  Workshop light  ')
    await coordinator.getByLabel('Inventory code', { exact: true }).fill('cam-002')
