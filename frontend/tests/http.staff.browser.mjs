async function apiStudent(tag) {
  const credentials = newStudent(tag)
  const registered = await api(stack, '/api/v1/auth/register', { method: 'POST', body: credentials })
  assert.equal(registered.status, 201)
  return { ...credentials, token: registered.json.token }
}
async function apiBooking(student, assetId, startDate, endDate, purpose) {
  const created = await api(stack, '/api/v1/bookings', { method: 'POST', token: student.token, body: { assetId, startDate, endDate, purpose } })
  assert.equal(created.status, 201, JSON.stringify(created.json))
  return created.json
}
